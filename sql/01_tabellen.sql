-- Data model for the subsidy application management prototype.
-- BETRIEB (farm) 1:n ANTRAG (application) 1:n ANTRAG_FLAECHE (area) n:1 KULTUR (crop)

CREATE TABLE BETRIEB (
    BETRIEB_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BETRIEBSNUMMER   VARCHAR2(30) NOT NULL UNIQUE,
    NAME             VARCHAR2(150) NOT NULL
);

CREATE TABLE KULTUR (
    KULTUR_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME             VARCHAR2(100) NOT NULL,
    SATZ_PRO_HEKTAR  NUMBER(10,2) NOT NULL
);

CREATE TABLE ANTRAG (
    ANTRAG_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BETRIEB_ID       NUMBER NOT NULL,
    JAHR             NUMBER(4) NOT NULL,
    EINREICHDATUM    DATE NOT NULL,
    STATUS           VARCHAR2(30) DEFAULT 'OFFEN' NOT NULL,
    FOERDERBETRAG    NUMBER(12,2),
    CONSTRAINT FK_ANTRAG_BETRIEB
        FOREIGN KEY (BETRIEB_ID)
        REFERENCES BETRIEB(BETRIEB_ID),
    CONSTRAINT UQ_ANTRAG_BETRIEB_JAHR
        UNIQUE (BETRIEB_ID, JAHR)
);

CREATE TABLE ANTRAG_FLAECHE (
    FLAECHE_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ANTRAG_ID        NUMBER NOT NULL,
    KULTUR_ID        NUMBER NOT NULL,
    HEKTAR           NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_FLAECHE_ANTRAG
        FOREIGN KEY (ANTRAG_ID)
        REFERENCES ANTRAG(ANTRAG_ID),
    CONSTRAINT FK_FLAECHE_KULTUR
        FOREIGN KEY (KULTUR_ID)
        REFERENCES KULTUR(KULTUR_ID),
    CONSTRAINT CK_FLAECHE_HEKTAR
        CHECK (HEKTAR > 0)
);

-- UQ_ANTRAG_BETRIEB_JAHR ensures a farm can only have one application per year.
-- CK_FLAECHE_HEKTAR ensures only positive area sizes can be stored.
